"""High-level skill options compiled into fixed low-level actions."""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any

from ..models import Action, ActionKind, Decision, RobotState


class SkillOption(str, Enum):
    INSPECT_ROOM = "inspect_room"
    MOVE_CLOSER = "move_closer"
    ASK_USER = "ask_user"
    TURN_AC = "turn_ac"
    ALARM = "alarm"
    WAIT = "wait"


@dataclass(frozen=True, slots=True)
class OptionStep:
    """One manager decision; parameters are still untrusted proposals."""

    option: SkillOption
    parameters: dict[str, Any] = field(default_factory=dict)
    reason: str = ""


@dataclass(frozen=True, slots=True)
class HighLevelPlan:
    steps: tuple[OptionStep, ...]
    response: str | None = None
    rationale: str = ""


@dataclass(frozen=True, slots=True)
class OptionDefinition:
    """Options abstraction O=(I, pi, beta) without claiming learned HRL."""

    option: SkillOption
    initiation: str
    fixed_policy: str
    termination: str


